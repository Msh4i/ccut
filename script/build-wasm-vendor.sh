#!/usr/bin/env bash
# Rebuilds the vendored `opencut-wasm` package (packages/opencut-wasm) from
# rust/wasm. This is the ONE way the wasm the app runs is built: the web app
# and the tests import `opencut-wasm` from this workspace package, not from
# npm. See packages/opencut-wasm/README.md.
#
# Usage: script/build-wasm-vendor.sh [--allow-dirty]
#   --allow-dirty  build even when rust/, Cargo.toml or Cargo.lock have
#                  uncommitted changes (the README then says "dirty").
# Environment:
#   OPENCUT_WASM_VERSION  package version (default 0.2.10-ccut.1)
#   CARGO_TARGET_DIR      honoured (reuse compiled dependencies)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CRATE="$ROOT/rust/wasm"
VENDOR="$ROOT/packages/opencut-wasm"
VERSION="${OPENCUT_WASM_VERSION:-0.2.10-ccut.1}"
ALLOW_DIRTY=0

for arg in "$@"; do
	case "$arg" in
		--allow-dirty) ALLOW_DIRTY=1 ;;
		*)
			echo "unknown argument: $arg" >&2
			exit 2
			;;
	esac
done

fail() {
	echo "build-wasm-vendor: $*" >&2
	exit 1
}

for tool in git cargo rustc wasm-pack wasm-bindgen wasm-opt; do
	command -v "$tool" >/dev/null 2>&1 || fail "missing tool: $tool"
done

if command -v rustup >/dev/null 2>&1; then
	rustup target list --installed | grep -qx "wasm32-unknown-unknown" ||
		fail "the wasm32-unknown-unknown target is not installed (rustup target add wasm32-unknown-unknown)"
fi

# wasm-bindgen's CLI must be the exact version of the crate in Cargo.lock,
# otherwise the generated glue does not match the wasm.
LOCK_BINDGEN="$(awk '$0 == "name = \"wasm-bindgen\"" { getline; gsub(/version = |"/, ""); print; exit }' "$ROOT/Cargo.lock")"
CLI_BINDGEN="$(wasm-bindgen --version | awk '{ print $2 }')"
[ -n "$LOCK_BINDGEN" ] || fail "wasm-bindgen not found in Cargo.lock"
[ "$LOCK_BINDGEN" = "$CLI_BINDGEN" ] ||
	fail "wasm-bindgen CLI $CLI_BINDGEN does not match Cargo.lock $LOCK_BINDGEN (cargo install wasm-bindgen-cli --version $LOCK_BINDGEN)"

SOURCE_STATE="clean"
if [ -n "$(git -C "$ROOT" status --porcelain -- rust Cargo.toml Cargo.lock)" ]; then
	[ "$ALLOW_DIRTY" = 1 ] ||
		fail "rust/, Cargo.toml or Cargo.lock have uncommitted changes: commit them first (or pass --allow-dirty)"
	SOURCE_STATE="dirty (uncommitted changes in rust/, Cargo.toml or Cargo.lock)"
fi
SOURCE_COMMIT="$(git -C "$ROOT" rev-parse HEAD)"
SOURCE_TREE="$(git -C "$ROOT" rev-parse HEAD:rust)"

OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT

# --no-opt: wasm-opt runs below with the version recorded in the README
# (wasm-pack would otherwise use or download its own binaryen).
wasm-pack build "$CRATE" \
	--target bundler \
	--release \
	--no-opt \
	--out-dir "$OUT/pkg" \
	--out-name opencut_wasm

wasm-opt -O "$OUT/pkg/opencut_wasm_bg.wasm" -o "$OUT/opencut_wasm_bg.wasm"

mkdir -p "$VENDOR"
cp "$OUT/pkg/opencut_wasm.js" "$VENDOR/opencut_wasm.js"
cp "$OUT/pkg/opencut_wasm_bg.js" "$VENDOR/opencut_wasm_bg.js"
cp "$OUT/pkg/opencut_wasm.d.ts" "$VENDOR/opencut_wasm.d.ts"
cp "$OUT/opencut_wasm_bg.wasm" "$VENDOR/opencut_wasm_bg.wasm"

# Same fields as the published opencut-wasm@0.2.10 package.json, plus
# "private" so the vendored build can never be published by mistake.
cat >"$VENDOR/package.json" <<EOF
{
  "name": "opencut-wasm",
  "type": "module",
  "description": "Shared video editor logic compiled to WebAssembly (Ccut vendored build of rust/wasm)",
  "version": "$VERSION",
  "license": "MIT",
  "private": true,
  "repository": {
    "type": "git",
    "url": "https://github.com/opencut/opencut"
  },
  "files": [
    "opencut_wasm_bg.wasm",
    "opencut_wasm.js",
    "opencut_wasm_bg.js",
    "opencut_wasm.d.ts"
  ],
  "main": "opencut_wasm.js",
  "types": "opencut_wasm.d.ts",
  "sideEffects": [
    "./opencut_wasm.js",
    "./snippets/*"
  ]
}
EOF

WASM_SHA256="$(sha256sum "$VENDOR/opencut_wasm_bg.wasm" | awk '{ print $1 }')"
WASM_BYTES="$(wc -c <"$VENDOR/opencut_wasm_bg.wasm" | tr -d ' ')"

cat >"$VENDOR/README.md" <<EOF
# opencut-wasm (vendored Ccut build)

The compiled \`rust/wasm\` crate (compositor, effects, masks, time) that the
web app imports as \`opencut-wasm\`. It replaces the published npm package
\`opencut-wasm@0.2.10\` because Ccut's compositor has changes the published
package does not have (3D layers: perspective placement by a homography,
and the shaders of the time-based effects and filters).

Generated by \`script/build-wasm-vendor.sh\`: do not edit these files by hand.

## Build of the files in this folder

| | |
|---|---|
| Package version | \`$VERSION\` |
| Source commit (HEAD when built) | \`$SOURCE_COMMIT\` |
| Source tree \`rust/\` at that commit | \`$SOURCE_TREE\` |
| Working tree | $SOURCE_STATE |
| rustc | \`$(rustc --version)\` |
| cargo | \`$(cargo --version)\` |
| wasm-pack | \`$(wasm-pack --version)\` |
| wasm-bindgen | \`$CLI_BINDGEN\` (Cargo.lock: \`$LOCK_BINDGEN\`) |
| wasm-opt | \`$(wasm-opt --version)\`, flags \`-O\` |
| opencut_wasm_bg.wasm | $WASM_BYTES bytes, sha256 \`$WASM_SHA256\` |

## Rebuild (after changing anything under \`rust/\`)

Needs Rust with the \`wasm32-unknown-unknown\` target, \`wasm-pack\`,
\`wasm-bindgen-cli\` at the version in \`Cargo.lock\`, and \`wasm-opt\` (binaryen).

1. Commit the Rust change.
2. From the repo root: \`script/build-wasm-vendor.sh\`
3. \`bun install\` (the workspace link does not change; the lockfile only
   changes when the version changes), then \`bun run qa\`.
4. Commit \`packages/opencut-wasm/\`.

## Going back to the npm package

1. In the root \`package.json\` and \`apps/web/package.json\`, set
   \`"opencut-wasm": "^0.2.10"\` again (instead of \`"workspace:*"\`).
2. Delete \`packages/opencut-wasm/\`.
3. \`bun install\` (updates \`bun.lock\`), then \`bun run qa\`.

The published package has no 3D-layer support: 3D layers would then be drawn
with their 2D bounding box instead of in perspective.
EOF

echo "build-wasm-vendor: wrote $VENDOR ($WASM_BYTES bytes wasm, sha256 $WASM_SHA256, source $SOURCE_COMMIT, $SOURCE_STATE)"
